#!/usr/bin/env python3
"""Generate or check the Fortran module dependencies in source/src/Makefile.am.

Each object of libsfincs.la must be built after the objects that provide the
modules it uses, otherwise "make -j" fails with "Cannot open module file".
This script reads libsfincs_la_SOURCES, scans the sources for "module" and
"use" statements and writes the rules between the BEGIN/END marker lines.

    python3 build_scripts/fortran_module_deps.py           # update src/Makefile.am
    python3 build_scripts/fortran_module_deps.py --check   # exit 1 if it is out of date

Run it from the source directory (or pass --makefile) after adding or removing
a source file or a "use" statement.
"""
import argparse
import pathlib
import re
import sys

BEGIN = '# BEGIN Fortran module dependencies (generated by build_scripts/fortran_module_deps.py)'
END = '# END Fortran module dependencies'

# Modules that do not come from libsfincs_la_SOURCES: compiler intrinsics and
# netcdf, which is built first in its own SUBDIRS entry (netcdf-fortran).
EXTERNAL = {'iso_c_binding', 'iso_fortran_env', 'ieee_arithmetic', 'ieee_exceptions',
            'omp_lib', 'openacc', 'netcdf'}

MODULE_RE = re.compile(r'^\s*module\s+(?!procedure\b|subroutine\b|function\b)(\w+)\s*$', re.I)
USE_RE = re.compile(r'^\s*use\s*(?:,\s*(?:non_)?intrinsic\s*)?(?:::\s*|\s+)(\w+)', re.I)


def sources(makefile_text):
    """Return the entries of libsfincs_la_SOURCES in order."""
    match = re.search(r'^libsfincs_la_SOURCES\s*=((?:.*\\\n)*.*)$', makefile_text, re.M)
    return [s for s in match.group(1).replace('\\', ' ').split()]


def resolve(srcdir, name):
    """Source file on disk (the list may give .f90 for a .F90 file)."""
    path = srcdir / name
    if not path.exists():
        path = path.with_suffix(path.suffix.swapcase())
    return path


def scan(path):
    """Modules defined and used in one source file (comments stripped)."""
    defined, used = set(), set()
    for line in path.read_text(encoding='utf-8-sig', errors='replace').splitlines():
        line = line.split('!', 1)[0]
        if m := MODULE_RE.match(line):
            defined.add(m.group(1).lower())
        elif m := USE_RE.match(line):
            used.add(m.group(1).lower())
    return defined, used - defined


def rules(srcdir, names):
    """Dependency rules "a.lo: b.lo c.lo" and the list of unknown modules."""
    obj = {n: re.sub(r'\.[fF]90$', '.lo', n) for n in names}
    scanned = {n: scan(resolve(srcdir, n)) for n in names}
    provider = {mod: n for n, (defined, _) in scanned.items() for mod in defined}
    out, unknown = [], []
    for n in names:
        deps = []
        for mod in sorted(scanned[n][1]):
            if mod in provider:
                deps.append(obj[provider[mod]])
            elif mod not in EXTERNAL:
                unknown.append(f'{n}: use {mod}')
        deps = sorted(set(deps) - {obj[n]}, key=list(obj.values()).index)
        if deps:
            out.append(wrap(obj[n] + ':', deps))
    return out, unknown


def wrap(target, deps, width=100):
    lines, line = [], target
    for d in deps:
        if len(line) + 1 + len(d) > width:
            lines.append(line + ' \\')
            line = '\t'
        line += ('' if line == '\t' else ' ') + d
    return '\n'.join(lines + [line])


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--makefile', default='src/Makefile.am')
    parser.add_argument('--check', action='store_true', help='only check, do not write')
    args = parser.parse_args()
    makefile = pathlib.Path(args.makefile)
    text = makefile.read_text()
    block, unknown = rules(makefile.parent, sources(text))
    for u in unknown:
        print(f'unknown module (not in libsfincs_la_SOURCES): {u}', file=sys.stderr)
    new = BEGIN + '\n' + '\n'.join(block) + '\n' + END
    old = re.search(re.escape(BEGIN) + r'.*?' + re.escape(END), text, re.S)
    if old is None:
        sys.exit(f'{makefile}: marker lines not found')
    if args.check:
        ok = old.group(0) == new and not unknown
        print(f'{makefile}: module dependencies {"up to date" if ok else "OUT OF DATE"}')
        sys.exit(0 if ok else 1)
    makefile.write_text(text[:old.start()] + new + text[old.end():])
    print(f'{makefile}: {len(block)} rules written')


if __name__ == '__main__':
    main()
